type WorldName = 'world-1' | 'world-2' | 'world-3' | 'world-4' | 'world-5' | 'world-6';
type ActorName = 'anonymous' | 'owner' | 'manager' | 'pm' | 'user';
type SuiteName = 'worlds' | 'work-unit-overrides' | 'pivot' | 'invitations';
type ConfigName = 'mock' | 'live' | 'local-proxy' | 'controlled';
type Layer = 'mock' | 'visual' | 'live' | 'local-proxy' | 'controlled';
type Tier = 'mr' | 'full' | 'live' | 'local-proxy';

type E2ECoverage = {
  kind: 'e2e';
  id: string;
  backfill: boolean;
  suite: SuiteName;
  config: ConfigName;
  layer: Layer;
  tier: Tier;
  project: string;
  spec: string;
  title: string;
  target:
    | { world: WorldName; actor: ActorName }
    | { environment: 'live' | 'local-proxy' | 'controlled'; actors: ActorName[] };
};

type GateCoverage = {
  kind: 'gate';
  id: string;
  backfill: boolean;
  reason: string;
  command: string;
  evidence:
    | { type: 'technical'; repository: string; job: string }
    | {
        type: 'external';
        provider: 'gitlab';
        projectId: string;
        shaEnv: string;
        job: string;
        artifact: string;
      }
    | {
        type: 'external';
        provider: 'github';
        repository: string;
        shaEnv: string;
        workflow: string;
        event: 'push';
        branch: string;
        job: string;
        artifact: string;
        file: string;
        evidenceProvider: string;
        providerEndpoint: string;
        model: string;
        configSha256: string;
        inventorySha256: string;
        expectedCases: number;
      };
};

type InfrastructureCoverage = {
  kind: 'infrastructure';
  id: 'CT-530';
  backfill: false;
  contracts: string[];
  command: string;
};

type PendingInfrastructureCoverage = {
  kind: 'pending-infrastructure';
  id: 'CT-521';
  backfill: false;
  status: 'blocked-unexecuted';
  reason: string;
  command: string;
  requires: readonly string[];
};

type Coverage = E2ECoverage | GateCoverage | InfrastructureCoverage | PendingInfrastructureCoverage;

type ConfigDefinition = {
  file: string;
  tagPolicy: 'primary-tag' | 'config-owned';
  targets: Array<{ project: string; tier: Tier; ciJob: string }>;
};

type SuiteDefinition = {
  configs: Partial<Record<ConfigName, ConfigDefinition>>;
};

